<h1>Manual de Inspección y Operaciones de Campo: Técnicos</h1>

<h2>1. Perfil del Técnico y Firma Digital</h2>
<p>Como <strong>Técnico Inspector de Campo</strong>, su función es constatar las condiciones de Higiene, Seguridad y Medio Ambiente (HyS) en las sedes cliente, registrar evidencias y certificar su presencia física en terreno.</p>
<h3>Carga Inicial de la Firma Digital</h3>
<p>Para que sus inspecciones y constancias de visita tengan validez legal, debe registrar su firma de perfil:</p>
<ol>
    <li>En la esquina superior derecha, haga clic en su usuario y seleccione <strong>"Mi Perfil"</strong>.</li>
    <li>Diríjase a la sección <strong>"Firma Digital de Perfil"</strong>.</li>
    <li>Trace su firma sobre el panel táctil.</li>
    <li>Guarde los cambios. Su firma quedará en estado <strong>"en revisión"</strong> hasta que su Gestor Titular la apruebe.</li>
    <li>Una vez aprobada, su firma se estampará de forma inmutable en todas las inspecciones que ejecute.</li>
</ol>

<hr>

<h2>2. Consola Táctica de Campo</h2>
<p>La consola de operaciones de campo está organizada en tres secciones:</p>
<pre>┌─────────────────────────────────────────────────────────────┐
│                 CONSOLA DE CAMPO TÁCTICA                    │
├───────────────────┬─────────────────────┬───────────────────┤
│    🎯 MISIONES    │     📚 EDUCACIÓN     │    📊 MÉTRICAS    │
│   (Inspecciones)  │   (Capacitaciones)  │    (Informes)     │
└───────────────────┴─────────────────────┴───────────────────┘</pre>
<h3>🎯 Misiones (Inspecciones)</h3>
<ul>
    <li>Muestra los checklists y auditorías asignadas para la jornada.</li>
    <li>Indicadores de cumplimiento: checklists completados y ratio de conformidades.</li>
    <li>Acceso al selector de acciones para iniciar ejecuciones libres o basadas en el Plan Anual.</li>
</ul>
<h3>📚 Educación (Capacitaciones)</h3>
<ul>
    <li>Charlas de seguridad y capacitaciones asignadas por sede.</li>
    <li>Registro de asistencia con DNI y firma digital de cada participante.</li>
</ul>
<h3>📊 Métricas (Informes)</h3>
<ul>
    <li>Espacio para redactar borradores de Informes Maestros mensuales y registrar avances de gabinete.</li>
</ul>

<hr>

<h2>3. Control de Visitas con Validación GPS</h2>
<p>Todas las inspecciones deben ejecutarse bajo una <strong>Visita Presencial Activa</strong> que certifique su presencia física en la planta del cliente.</p>
<h3>Paso 1: Inicio de Visita (Entrada)</h3>
<ol>
    <li>En la consola, ingrese a <strong>"Mis Visitas"</strong> y seleccione la Sede Cliente.</li>
    <li>Presione el botón <strong>"Iniciar Visita"</strong>.</li>
    <li>El navegador solicitará acceso a su ubicación GPS. Otorgue el permiso obligatoriamente.</li>
    <li>El sistema registrará sus coordenadas de ingreso y verificará que se encuentre dentro del radio de tolerancia de la sede (generalmente 500 metros).</li>
</ol>
<h3>Paso 2: Cierre de Visita (Salida)</h3>
<ol>
    <li>Al finalizar las inspecciones del día, presione <strong>"Finalizar Visita"</strong>.</li>
    <li>El sistema capturará nuevamente su ubicación, calculará las horas de campo reales y marcará la presencia GPS como confirmada.</li>
</ol>
<blockquote>🏔️ <strong>Operación en Sedes Mineras 24/7:</strong> Si la sede opera en modalidad continua, las restricciones de horarios y días no laborales quedan desactivadas automáticamente.</blockquote>

<hr>

<h2>4. Asistente de Llenado de Checklists</h2>
<h3>🕒 Campos de Tiempo</h3>
<ul>
    <li>Los campos de hora y fecha están adaptados a pantallas táctiles.</li>
    <li>Botones <strong>"🕒 Hora Actual"</strong> y <strong>"📅 Ahora"</strong> para inyectar la fecha y hora con un solo toque.</li>
</ul>
<h3>⌚ Inmutabilidad de Tiempo</h3>
<ul>
    <li>Para evitar manipulaciones de horario, el servidor descarta cualquier marca de tiempo enviada desde el dispositivo y aplica la hora exacta del servidor al guardar.</li>
    <li>El badge <strong>"⌚ Tiempo Real (Sync Servidor)"</strong> en la cabecera del Wizard confirma que esta protección está activa.</li>
</ul>
<h3>🚨 Intercepción por Falla Crítica</h3>
<p>Si durante el llenado se responde una opción marcada como desvío grave:</p>
<ol>
    <li>Al presionar <strong>"Siguiente Sección"</strong>, el sistema mostrará un aviso de advertencia.</li>
    <li>Se presentan dos opciones:
        <ul>
            <li><strong>Continuar Inspección:</strong> Seguir evaluando los puntos restantes.</li>
            <li><strong>Rechazar y Finalizar:</strong> Las preguntas restantes se completan automáticamente indicando que no pudieron evaluarse por la falla detectada, y se pasa directamente al cierre con firmas.</li>
        </ul>
    </li>
</ol>

<hr>

<h2>5. Registro de Evidencias: Hallazgos e Incidentes</h2>
<h3>Reporte Rápido en Visita Activa</h3>
<p>Si durante un recorrido detecta una condición insegura:</p>
<ol>
    <li>Abra el formulario de <strong>Nuevo Hallazgo</strong> o <strong>Nuevo Incidente</strong>.</li>
    <li>Si hay una visita activa, la Sede se fijará automáticamente para evitar errores de asociación.</li>
    <li>Al guardar, el sistema lo devolverá automáticamente a la consola de su visita en progreso.</li>
</ol>
<h3>📸 Evidencia Fotográfica</h3>
<ul>
    <li>Puede seleccionar y subir fotos de forma secuencial sin perder las selecciones anteriores.</li>
    <li>Cada miniatura incluye un botón <strong>"✕"</strong> para eliminar fotos equivocadas antes de enviar el reporte.</li>
</ul>

<hr>

<h2>6. Ejecución de Capacitaciones en Vivo</h2>
<ol>
    <li>Seleccione la capacitación asignada e inicie la sesión en vivo.</li>
    <li>Presione <strong>"+ Agregar Asistente"</strong> e ingrese Nombres, Apellidos, Puesto y Nº de Documento (obligatorio).</li>
    <li>Solicite al asistente que firme directamente en la pantalla.</li>
    <li>Al finalizar, presione <strong>"Finalizar Capacitación"</strong> para registrar la duración real y cerrar la sesión.</li>
</ol>
